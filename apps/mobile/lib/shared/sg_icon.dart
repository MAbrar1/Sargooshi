  static const Set<SgIconName> directional = {
    SgIconName.back,
    SgIconName.forward,
    SgIconName.send,
    SgIconName.undo,
    SgIconName.redo,
  };

  static IconData resolve(
    SgIconName name, {
    bool selected = false,
    bool emptyState = false,
    double size = SargoshiIconSize.standard,
  }) {
    if (emptyState) return _duotone[name]!;
    if (selected) return _fill[name]!;
    if (size < SargoshiIconSize.boldThreshold) return _bold[name]!;
    return _regular[name]!;
  }

  @override
  Widget build(BuildContext context) {
    final textDirection = Directionality.of(context);
    final icon = PhosphorIcon(
      resolve(
        name,
        selected: selected,
        emptyState: emptyState,
        size: size,
      ),
      size: size,
      color: color ?? Theme.of(context).iconTheme.color,
      semanticLabel: semanticLabel,
      textDirection: textDirection,
      duotoneSecondaryColor: color,
      duotoneSecondaryOpacity: SargoshiIconSize.duotoneSecondaryOpacity,
    );

    // The Phosphor package's canonical glyph data is reused directly. Only
    // directional Sargoshi actions are mirrored, and only in RTL layouts.
    if (textDirection != TextDirection.rtl || !directional.contains(name)) {
      return icon;
    }
    return Transform.flip(
      key: const ValueKey<String>('sg-icon-rtl-directional'),
      flipX: true,
      child: icon,
    );
  }
